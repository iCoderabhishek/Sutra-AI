// Saves a run's final answer as a Markdown file on the user's machine.
// Files go to ~/Downloads when it exists, otherwise the home folder, and are
// never overwritten: a numbered suffix is added instead.

// reportMarkdown turns a structured report into a standalone .md document.
func reportMarkdown(r *api.Report, agentName, runID string, when time.Time) string {
	var b strings.Builder
	line := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }

	line("# %s", oneLine(r.Headline))
	line("")
	meta := []string{"**Agent:** " + oneLine(agentName), "**Date:** " + when.Format("2006-01-02 15:04")}
	if r.Outcome != "" {
		meta = append(meta, "**Outcome:** "+oneLine(r.Outcome))
	}
	if r.Confidence != "" {
		meta = append(meta, "**Confidence:** "+oneLine(r.Confidence))
	}
	meta = append(meta, "**Run:** `"+oneLine(runID)+"`")
	line("%s", strings.Join(meta, " · "))
	line("")
	line("%s", clean(r.Summary))

	if len(r.Findings) > 0 {
		line("")
		line("## Key findings")
		for _, f := range r.Findings {
			line("")
			line("### %s", oneLine(f.Title))
			line("")
			for _, p := range f.Points {
				line("- %s", oneLine(p))
			}
		}
	}

	if len(r.Sources) > 0 {
		line("")
		line("## Sources")
		line("")
		for i, s := range r.Sources {
			item := oneLine(s.Name)
			if s.URL != nil && safeURL(*s.URL) {
				item = fmt.Sprintf("[%s](<%s>)", item, strings.TrimSpace(*s.URL))
			}
			if s.Date != nil && strings.TrimSpace(*s.Date) != "" {
				item += " · " + oneLine(*s.Date)
			}
			line("%d. %s", i+1, item)
		}
	}

	if strings.TrimSpace(r.Takeaway) != "" {
		line("")
		line("## Takeaway")
		line("")
		line("> %s", oneLine(r.Takeaway))
	}

	line("")
	line("---")
	line("_Generated by Sutra AI_")
	return b.String()
}

// plainMarkdown wraps older free-text answers, which are already markdown-ish.
func plainMarkdown(text, agentName, runID string, when time.Time) string {
	return fmt.Sprintf("# %s\n\n**Date:** %s · **Run:** `%s`\n\n%s\n\n---\n_Generated by Sutra AI_\n",
		oneLine(agentName), when.Format("2006-01-02 15:04"), oneLine(runID), clean(text))
}

// clean removes terminal control sequences but keeps line breaks.
func clean(s string) string { return strings.TrimSpace(sanitize(s)) }

// oneLine keeps a value on a single line so it can't break the document layout.
func oneLine(s string) string { return strings.Join(strings.Fields(sanitize(s)), " ") }

// safeURL only links http(s) URLs, so a report can't plant javascript: links.
func safeURL(raw string) bool {
	u, err := url.Parse(strings.TrimSpace(raw))
	return err == nil && (u.Scheme == "http" || u.Scheme == "https") && u.Host != "" &&
		!strings.ContainsAny(raw, "<>\n")
}

// saveDir is where exports go: ~/Downloads if present, else the home folder,
// else the current directory.
func saveDir() string {
	home, err := os.UserHomeDir()
	if err != nil {
		return "."
	}
	if dl := filepath.Join(home, "Downloads"); isDir(dl) {
		return dl
	}
	return home
}

func isDir(p string) bool {
	info, err := os.Stat(p)
	return err == nil && info.IsDir()
}

var slugUnsafe = regexp.MustCompile(`[^a-z0-9]+`)

// exportName builds "<agent>-<date>-<run>" with only filename-safe characters.
func exportName(agentName, runID string, when time.Time) string {
	slug := strings.Trim(slugUnsafe.ReplaceAllString(strings.ToLower(agentName), "-"), "-")
	if slug == "" {
		slug = "sutra-report"
	}
	if len(slug) > 40 { // slug is ASCII, so byte length is safe
		slug = strings.TrimRight(slug[:40], "-")
	}
	run := slugUnsafe.ReplaceAllString(strings.ToLower(shortID(runID)), "")
	name := slug + "-" + when.Format("2006-01-02")
	if run != "" {
		name += "-" + run
	}
	return name
}

// writeExport creates dir/base.md, or base-2.md and so on if it already exists.
func writeExport(dir, base, content string) (string, error) {
	for i := 1; i <= 100; i++ {
		name := base + ".md"
		if i > 1 {
			name = fmt.Sprintf("%s-%d.md", base, i)
		}
		path := filepath.Join(dir, name)
		f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
		if errors.Is(err, os.ErrExist) {
			continue
		}
		if err != nil {
			return "", err
		}
		if _, err := f.WriteString(content); err != nil {
			f.Close()
			return "", err
		}
		return path, f.Close()
	}
	return "", fmt.Errorf("too many files named %s in %s", base, dir)
}
